def main(
    all_pairs: bool,
    pairs: Optional[str],
    resume: bool,
    batch_size: int,
    delay: float,
    max_retries: int,
    checkpoint_interval: int,
    verbose: bool,
    max_concurrent: int,
    requests_per_second: float,
    adaptive_rate: bool,
    circuit_breaker: bool,
    batch_db_writes: bool,
    performance_monitoring: bool,
    sequential: bool,
    source: str,
    db_languages: Optional[str],
    show_stats: bool,
):
    """
    Populate database with word translations for all language pairs.

    This script provides high-performance parallel translation processing
    with intelligent rate limiting, error handling, and progress monitoring.

    Examples:

        # Process all language pairs with default parallel settings
        python scripts/populate_database.py --all-pairs

        # Process specific pairs with high performance
        python scripts/populate_database.py --pairs english-polish,polish-english --max-concurrent 50

        # Use database words for Russian and English (cost-optimized)
        python scripts/populate_database.py --source database --db-languages russian,english --all-pairs

        # Mixed mode: database for some languages, files for others
        python scripts/populate_database.py --source mixed --db-languages russian,english --pairs russian-polish,english-spanish

        # Show database word statistics
        python scripts/populate_database.py --show-stats

        # Conservative processing with circuit breaker
        python scripts/populate_database.py --pairs russian-english --max-concurrent 10 --circuit-breaker

        # Resume from checkpoint with monitoring
        python scripts/populate_database.py --resume --performance-monitoring
    """

    # Validate arguments
    if not all_pairs and not pairs:
        click.echo("Error: Must specify either --all-pairs or --pairs", err=True)
        raise click.Abort()

    if all_pairs and pairs:
        click.echo("Error: Cannot specify both --all-pairs and --pairs", err=True)
        raise click.Abort()
    # Parse database languages if provided
    parsed_db_languages = []
    if db_languages:
        parsed_db_languages = [lang.strip().lower() for lang in db_languages.split(",")]
        logger.info(f"Database languages specified: {parsed_db_languages}")

    # Handle show-stats option
    if show_stats:
        # Just show statistics and exit
        async def show_stats_only():
            populator = DatabasePopulator()
            try:
                await populator.initialize()
                await populator.show_database_statistics()
                return 0
            except Exception as e:
                logger.error(f"Failed to show statistics: {e}")
                return 1
            finally:
                await populator.cleanup()

        exit_code = asyncio.run(show_stats_only())
        sys.exit(exit_code)

    # Validate database source parameters
    if source in ["database", "mixed"] and not parsed_db_languages:
        click.echo(
            "Error: --db-languages must be specified when using database or mixed source",
            err=True,
        )
        raise click.Abort()

    # Run the population process
    exit_code = asyncio.run(
        run_population(
            all_pairs=all_pairs,
            pairs=pairs,
            resume=resume,
            batch_size=batch_size,
            delay=delay,
            max_retries=max_retries,
            checkpoint_interval=checkpoint_interval,
            verbose=verbose,
            max_concurrent=max_concurrent,
            requests_per_second=requests_per_second,
            adaptive_rate=adaptive_rate,
            circuit_breaker=circuit_breaker,
            batch_db_writes=batch_db_writes,
            performance_monitoring=performance_monitoring,
            sequential=sequential,
            source=source,
            db_languages=parsed_db_languages,
        )
    )

    sys.exit(exit_code)


