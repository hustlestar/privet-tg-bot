                f.write(f"Requests per second: {self.requests_per_second}\n")
                f.write(f"Adaptive rate limiting: {self.adaptive_rate}\n")
                f.write(f"Circuit breaker enabled: {self.circuit_breaker_enabled}\n")
                f.write(f"Performance monitoring: {self.performance_monitoring}\n\n")

                f.write("Overall Statistics:\n")
