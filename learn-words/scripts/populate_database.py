                f.write(f"Language pairs processed: {stats['total_pairs_processed']}\n")
                f.write(f"Words processed: {stats['total_words_processed']}\n")
                f.write(f"Words skipped (already existed): {stats['total_words_skipped']}\n")
                f.write(f"Errors: {stats['total_errors']}\n")
                f.write(f"Overall success rate: {stats['overall_success_rate']:.1f}%\n")

                # Add performance metrics if available
                if self.performance_monitor:
                    perf_summary = self.performance_monitor.get_summary()
                    f.write(f"Average API latency: {perf_summary['avg_api_latency']:.3f}s\n")
                    f.write(f"Cache hit rate: {perf_summary['cache_hit_rate']:.1%}\n")
                    f.write(f"Total API calls: {perf_summary['api_calls']}\n")

                f.write("\n")

                f.write("Language Pair Details:\n")
