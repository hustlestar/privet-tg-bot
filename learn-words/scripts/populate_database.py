    async def load_word_lists(self) -> Dict[str, List[Dict]]:
        """Load word lists based on configured source (files, database, or mixed)."""
        if self.word_source == "database":
            return await self.load_word_lists_from_database(self.db_languages or self.supported_languages)
        elif self.word_source == "mixed":
            return await self.load_word_lists_mixed(self.db_languages or [])
        else:  # files
            return self.load_word_lists_from_files()

    async def load_word_lists_from_database(self, languages: List[str]) -> Dict[str, List[Dict]]:
        """Load word lists from database for specified languages."""
        if not self.db:
            logger.error("Database not initialized")
            return {}

        try:
            word_lists = await self.db.get_words_by_languages(languages)

            # Log statistics
            for language, words in word_lists.items():
                logger.info(f"Loaded {len(words)} words for {language} from database")

            return word_lists

        except Exception as e:
            logger.error(f"Failed to load words from database: {e}")
            return {}

    async def load_word_lists_mixed(self, db_languages: List[str]) -> Dict[str, List[Dict]]:
        """Load word lists from both database and files."""
        word_lists = {}

        # Load from database for specified languages
        if db_languages:
            db_word_lists = await self.load_word_lists_from_database(db_languages)
            word_lists.update(db_word_lists)

        # Load from files for remaining languages
        file_languages = [lang for lang in self.supported_languages if lang not in db_languages]
        if file_languages:
            file_word_lists = self.load_word_lists_from_files(file_languages)
            word_lists.update(file_word_lists)

        return word_lists

    def load_word_lists_from_files(self, languages: List[str] = None) -> Dict[str, List[Dict]]:
        """Load word lists from JSON files for specified languages."""
        if languages is None:
            languages = self.supported_languages

        word_lists = {}

        for language in languages:
            # Look for word list files (try different counts)
            possible_files = [
                f"{language}_9700.json",
                f"{language}_5000.json",
                f"{language}_3000.json",
                f"{language}_1000.json",
                f"{language}_100.json",
                f"{language}.json",
            ]

            word_list_file = None
            for filename in possible_files:
                filepath = self.generated_lists_dir / filename
                if filepath.exists():
                    word_list_file = filepath
                    break

            if word_list_file:
                try:
                    with open(word_list_file, "r", encoding="utf-8") as f:
                        data = json.load(f)
                        word_lists[language] = data["words"]
                        logger.info(f"Loaded {len(data['words'])} words for {language} from {word_list_file.name}")
                except Exception as e:
                    logger.error(f"Failed to load word list for {language}: {e}")
            else:
                logger.warning(f"No word list found for {language}")

        return word_lists

