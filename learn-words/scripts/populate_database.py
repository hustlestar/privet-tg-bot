    def get_language_pairs(self, pairs_arg: Optional[str] = None) -> List[Tuple[str, str]]:
        """Get the list of language pairs to process."""
        if pairs_arg:
            # Parse specific pairs from argument
            pairs = []
            for pair_str in pairs_arg.split(","):
                pair_str = pair_str.strip()
                if "-" in pair_str:
                    from_lang, to_lang = pair_str.split("-", 1)
                    pairs.append((from_lang.strip(), to_lang.strip()))
                else:
                    logger.warning(f"Invalid pair format: {pair_str}")
            return pairs
        else:
            # Return all possible pairs
            return self.all_language_pairs

    def load_checkpoint(self, checkpoint_name: str) -> Optional[Dict]:
        """Load checkpoint data for resuming."""
        checkpoint_file = self.checkpoints_dir / f"{checkpoint_name}.json"

        if checkpoint_file.exists():
            try:
                with open(checkpoint_file, "r", encoding="utf-8") as f:
                    checkpoint_data = json.load(f)
                    logger.info(f"Loaded checkpoint: {checkpoint_file}")
                    return checkpoint_data
            except Exception as e:
                logger.error(f"Failed to load checkpoint {checkpoint_file}: {e}")

        return None

    def save_checkpoint(self, checkpoint_name: str, data: Dict):
        """Save checkpoint data for resuming."""
        checkpoint_file = self.checkpoints_dir / f"{checkpoint_name}.json"

        try:
            with open(checkpoint_file, "w", encoding="utf-8") as f:
                json.dump(data, f, indent=2, default=str)
                logger.info(f"Checkpoint saved: {checkpoint_file}")
        except Exception as e:
            logger.error(f"Failed to save checkpoint {checkpoint_file}: {e}")

    async def check_word_exists(
        self,
        word: str,
        from_lang: str,
        to_lang: str,
        native_language: Optional[str] = None,
    ) -> bool:
        """Check if a word translation already exists in the database."""
        try:
            # If native_language is not provided, use to_lang as default
            if native_language is None:
                native_language = to_lang

            existing_word = await self.db.get_word(
                word.lower().strip(),
                from_lang.lower(),
                to_lang.lower(),
                native_language.lower(),
            )
            return existing_word is not None
        except Exception as e:
            logger.warning(f"Error checking word existence: {e}")
            return False

    async def translate_and_save_word(
        self,
        word: str,
        from_lang: str,
        to_lang: str,
        user_native: str,
        user_learning: str,
        native_language: Optional[str] = None,
    ) -> bool:
        """Translate a word and save it to the database."""
        try:
            # Skip normalization and go straight to LLM as requested
            logger.debug(f"Translating '{word}' ({from_lang} -> {to_lang})")

            # Use the enhanced translation method
            # If native_language is not provided, use user_learning as default
            if native_language is None:
                native_language = user_native

            translation_data = await self.translator.translate_word_enhanced(
                word=word,
                from_language=from_lang,
                to_language=to_lang,
                user_native=user_native,
                user_learning=user_learning,
            )

            if translation_data:
                return True
            else:
                return False

        except Exception as e:
            logger.error(f"Error translating '{word}' ({from_lang} -> {to_lang}): {e}")
            return False

    async def _translate_with_retry(
        self,
        word: str,
        from_lang: str,
        to_lang: str,
        user_native: str,
        user_learning: str,
        max_retries: int = 3,
    ) -> bool:
        if from_lang == user_learning:
            return False
        """Translate a word with retry logic and exponential backoff."""
        for attempt in range(max_retries):
            try:
                success = await self.translate_and_save_word(word, from_lang, to_lang, user_native, user_learning, user_learning)
                return success
            except Exception as e:
                error_type = ErrorClassifier.classify_error(e)

                if error_type == "RATE_LIMIT":
                    # Exponential backoff for rate limits
                    wait_time = (2**attempt) + (0.1 * attempt)
                    logger.warning(f"Rate limit hit for '{word}', waiting {wait_time:.1f}s (attempt {attempt + 1})")
                    await asyncio.sleep(wait_time)
                elif attempt == max_retries - 1:
                    # Last attempt failed
                    logger.error(f"Failed to translate '{word}' after {max_retries} attempts: {e}")
                    return False
                else:
                    # Other errors - shorter wait
                    wait_time = 0.5 * (attempt + 1)
                    logger.warning(f"Translation error for '{word}', retrying in {wait_time:.1f}s: {e}")
                    await asyncio.sleep(wait_time)

        return False

    def _determine_native_language(self, from_lang: str, to_lang: str) -> str:
        """Determine the native language for a language pair.

        For language learning, we typically want one consistent native language.
        For example, for both 'russian-english' and 'english-russian' pairs,
        if the user is learning English, Russian should be the native language.
        """
        # Priority order for native languages (customize based on your use case)
        native_priority = ["russian", "polish", "spanish", "english"]

        # Check if either language is in our priority list
        for native_lang in native_priority:
            if native_lang in [from_lang, to_lang]:
                return native_lang

        # Fallback: use the first language alphabetically
        return min(from_lang, to_lang)

    async def process_batch_parallel_bidirectional(self, batch_plan: List[Dict], native_language: str, batch_index: int) -> Dict:
        """Process a batch of bidirectional translations with parallel processing."""

        batch_start_time = time.time()

        # Initialize parallel processing components
        semaphore = asyncio.Semaphore(self.max_concurrent)
        rate_limiter = TokenBucketRateLimiter(
            rate=self.requests_per_second,
            burst=self.max_concurrent,
            adaptive=self.adaptive_rate,
        )
        circuit_breaker = CircuitBreaker() if self.circuit_breaker_enabled else None

        # Statistics tracking
        stats = {
            "processed": 0,
            "skipped": 0,
            "errors": 0,
            "error_rate_limit": 0,
            "error_api_error": 0,
            "error_timeout": 0,
            "error_network": 0,
            "error_parse_error": 0,
            "error_unknown": 0,
        }

        # Create parallel translation tasks for bidirectional processing
        tasks = []
        for plan_item in batch_plan:
            task = asyncio.create_task(
                self.translate_word_parallel_bidirectional(
                    plan_item,
                    native_language,
                    semaphore,
                    rate_limiter,
                    circuit_breaker or CircuitBreaker(),
                    stats,
                )
            )
            tasks.append(task)

        # Execute all tasks concurrently with progress tracking
        results = []
        completed = 0

        # Process tasks as they complete
        for coro in asyncio.as_completed(tasks):
            try:
                result = await coro
                results.append(result)
                completed += 1

                # Log progress every 10 completions
                if completed % 10 == 0:
                    progress = completed / len(tasks) * 100
                    logger.info(f"Batch {batch_index}: {progress:.1f}% complete ({completed}/{len(tasks)})")

            except Exception as e:
                logger.error(f"Task failed in batch {batch_index}: {e}")
                results.append((False, "task_failed"))
                stats["errors"] += 1

        # Calculate batch statistics
        batch_duration = time.time() - batch_start_time
        throughput = len(batch_plan) / batch_duration if batch_duration > 0 else 0

        batch_stats = {
            "batch_index": batch_index,
            "total_words": len(batch_plan),
            "duration": batch_duration,
            "throughput": throughput,
            "concurrent_tasks": self.max_concurrent,
            **stats,
        }

        logger.info(
            f"Batch {batch_index} completed: {stats['processed']} processed, "
            f"{stats['skipped']} skipped, {stats['errors']} errors "
            f"in {batch_duration:.1f}s ({throughput:.1f} words/s)"
        )

        return batch_stats

    async def translate_word_parallel_bidirectional(
        self,
        plan_item: Dict,
        native_language: str,
        semaphore: asyncio.Semaphore,
        rate_limiter: TokenBucketRateLimiter,
        circuit_breaker: CircuitBreaker,
        stats: Dict,
    ) -> Tuple[bool, Optional[str]]:
        """Translate a single word with bidirectional parallel processing support."""

        async with semaphore:  # Limit concurrency
            word_entry = plan_item["word_entry"]
            word = word_entry["word"]
            source_lang = plan_item["source_lang"]
            target_lang = plan_item["target_lang"]
            direction = plan_item["direction"]

            try:
                # Check circuit breaker
                if await circuit_breaker.is_open():
                    stats["errors"] += 1
                    return False, "circuit_breaker_open"

                # Rate limiting
                await rate_limiter.acquire()

                # Record performance metrics
                if self.performance_monitor:
                    await self.performance_monitor.record_cache_miss()

                # Check cache first
                if await self.check_word_exists(word, source_lang, target_lang, native_language):
                    stats["skipped"] += 1
                    if self.performance_monitor:
                        await self.performance_monitor.record_cache_hit()
                    logger.debug(f"Word '{word}' ({direction}) already exists, skipping")
                    return True, "skipped"

                # Translate with retry logic
                api_start_time = time.time()
                success = await self._translate_with_retry(
                    word=word,
                    from_lang=source_lang,
                    to_lang=target_lang,
                    user_native=native_language,
                    user_learning=(target_lang if native_language == source_lang else source_lang),
                )
                api_duration = time.time() - api_start_time

                if success:
                    stats["processed"] += 1
                    await circuit_breaker.record_success()
                    rate_limiter.record_success()

                    if self.performance_monitor:
                        await self.performance_monitor.record_api_call(api_duration)

                    logger.debug(f"Successfully translated '{word}' ({direction})")
                    return True, "processed"
                else:
                    stats["errors"] += 1
                    await circuit_breaker.record_failure()
                    rate_limiter.record_error()
                    return False, "translation_failed"

            except Exception as e:
                error_type = ErrorClassifier.classify_error(e)
                stats["errors"] += 1
                stats[f"error_{error_type.lower()}"] += 1
                await circuit_breaker.record_failure()
                rate_limiter.record_error()

                if self.performance_monitor:
                    await self.performance_monitor.record_error(error_type)

                logger.error(f"Translation failed for '{word}' ({direction}): {e}")
                return False, error_type

